// 1) Bundles the browser app into public/app.js.
// 2) Embeds the files in public/ into the Worker (src/worker/static.gen.ts), so the
//    Worker serves them itself after the login check. One upload, nothing separate.
import { build } from "esbuild";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

await build({
  entryPoints: ["src/client/main.tsx"],
  bundle: true,
  format: "esm",
  target: "es2020",
  outfile: "public/app.js",
  minify: !process.argv.includes("--dev"),
  jsx: "automatic",
  jsxImportSource: "preact",
  logLevel: "info",
});

const TYPES = { html: "text/html; charset=utf-8", js: "text/javascript; charset=utf-8", css: "text/css; charset=utf-8", svg: "image/svg+xml" };
const files = {};
for (const name of readdirSync("public")) {
  const ext = name.split(".").pop();
  if (!TYPES[ext]) continue;
  const body = readFileSync(`public/${name}`, "utf8");
  files[`/${name}`] = { type: TYPES[ext], etag: `"${createHash("sha256").update(body).digest("hex").slice(0, 16)}"`, body };
}
writeFileSync("src/worker/static.gen.ts", `// Generated by scripts/build.mjs — do not edit.\nexport const STATIC: Record<string, { type: string; etag: string; body: string }> = ${JSON.stringify(files)};\n`);
console.log(`Embedded ${Object.keys(files).length} static files into the Worker.`);
