// 1) Bundles the browser app into public/ (app.js + lazily loaded chunks).
// 2) Embeds every file in public/ into the Worker (src/worker/static.gen.ts), so the
//    Worker serves them itself — one upload, nothing separate.
import { build } from "esbuild";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

rmSync("public/chunks", { recursive: true, force: true });
mkdirSync("public/fonts", { recursive: true });
copyFileSync("node_modules/temml/dist/Temml.woff2", "public/fonts/Temml.woff2");

const BUILD = Date.now().toString(36);
await build({
  entryPoints: { app: "src/client/main.tsx" },
  bundle: true,
  splitting: true,
  format: "esm",
  target: "es2020",
  outdir: "public",
  chunkNames: "chunks/[name]-[hash]",
  minify: !process.argv.includes("--dev"),
  jsx: "automatic",
  jsxImportSource: "preact",
  loader: { ".md": "text", ".css": "text" },
  define: { __BUILD__: JSON.stringify(BUILD) },
  logLevel: "info",
});

const TYPES = { html: "text/html; charset=utf-8", js: "text/javascript; charset=utf-8", css: "text/css; charset=utf-8", svg: "image/svg+xml", woff2: "font/woff2" };
const BINARY = new Set(["woff2"]);
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) { walk(path); continue; }
    const ext = name.split(".").pop();
    if (!TYPES[ext]) continue;
    const buf = readFileSync(path);
    const etag = `"${createHash("sha256").update(buf).digest("hex").slice(0, 16)}"`;
    const key = "/" + relative("public", path).split("\\").join("/");
    files[key] = BINARY.has(ext) ? { type: TYPES[ext], etag, b64: buf.toString("base64") } : { type: TYPES[ext], etag, body: buf.toString("utf8") };
  }
};
walk("public");
writeFileSync("src/worker/static.gen.ts", `// Generated by scripts/build.mjs — do not edit.\nexport const BUILD = ${JSON.stringify(BUILD)};\nexport const STATIC: Record<string, { type: string; etag: string; body?: string; b64?: string }> = ${JSON.stringify(files)};\n`);
console.log(`Embedded ${Object.keys(files).length} static files into the Worker.`);
